"""
geometry_core.py
=================

Единая параметрическая модель геометрии лабораторного Т-образного
микрофлюидного реактора (чертёж "1. ЛАБОРАТОРНЫЙ Т-ОБРАЗНЫЙ
МИКРОФЛЮИДНЫЙ РЕАКТОР ДЛЯ ГЕНЕРАЦИИ КАПЕЛЬ").

Модуль не зависит ни от VTK, ни от CadQuery/OpenCASCADE -- он только
описывает геометрию в виде списка прямоугольных параллелепипедов
(боксов) с координатами в миллиметрах. Оба бэкенда экспорта
(STL через VTK, STEP через CadQuery/OCC) строят тело из ОДНОГО
и того же набора боксов, поэтому результаты гарантированно совпадают.

Система координат
------------------
    X — вдоль главного (горизонтального) канала, 0 = левый вход
    Y — вдоль бокового (вертикального на чертеже) канала, 0 = ось
        главного канала
    Z — по высоте (глубине) канала, 0 = дно

Геометрия канала (см. чертёж, вид "а) Вид сверху (план)"):
    - Главный канал: длина L1+L3, ширина w, идёт по оси X,
      центрирован по Y (от -w/2 до +w/2).
    - Т-образование (стык) находится на расстоянии L1 от левого
      торца (правый торец, соответственно, на L1+L3).
    - Боковой (дозирующий) канал шириной wd подходит к главному
      каналу под углом 90° со стороны Y<0. Его длина L2 отсчитана
      от входного торца до наружной стенки главного канала
      (т.е. до Y = -w/2), как показано простановкой размера на
      чертеже.
    - Высота (глубина) канала h одинакова везде (см. сечение А-А).

Три порта (входа/выхода) реактора:
    inlet_1  — левый торец главного канала  (нормаль -X)
    outlet   — правый торец главного канала (нормаль +X)
    inlet_2  — торец бокового канала        (нормаль -Y)

Величины по умолчанию взяты прямо с чертежа (в мм):
    L1 = 10,  L2 = 8,  L3 = 30      (мм)
    w  = 0.2, wd = 0.1, h = 0.1     (мм)   [= 200, 100, 100 мкм]
"""

from dataclasses import dataclass, field
from typing import Dict, List, Tuple

# Прямоугольный параллелепипед, заданный диапазонами координат (мм)
BoxSpec = Tuple[float, float, float, float, float, float]  # xmin,xmax,ymin,ymax,zmin,zmax


@dataclass
class TReactorParams:
    """Параметры Т-образного реактора (все размеры в мм).

    Соответствие обозначениям на чертеже (в скобках — значение
    на чертеже в мкм/мм, для справки):
    """
    L1: float = 10.0     # длина левого плеча главного канала, мм
    L2: float = 8.0      # длина бокового (дозирующего) канала, мм
    L3: float = 30.0     # длина правого плеча главного канала, мм
    w: float = 0.2        # ширина главного канала, мм (200 мкм)
    wd: float = 0.1       # ширина бокового канала, мм (100 мкм)
    h: float = 0.1        # высота (глубина) канала, мм (100 мкм)

    # Технологические параметры инструмента (не с чертежа):
    cap_thickness: float = 0.3   # толщина "крышек" портов, мм
    # доля перекрытия бокового канала с главным (для чистого
    # булева объединения без "щели"); не влияет на итоговую длину
    # L2, т.к. отсчитывается уже ВНУТРИ главного канала.
    junction_overlap: float = 0.0

    def __post_init__(self):
        for name in ("L1", "L2", "L3", "w", "wd", "h", "cap_thickness"):
            if getattr(self, name) <= 0:
                raise ValueError(f"Параметр {name} должен быть положительным")
        if self.wd > self.w:
            raise ValueError("Ширина бокового канала wd не может превышать ширину главного канала w")

    # -- производные величины -------------------------------------------------
    @property
    def total_length(self) -> float:
        """Полная длина главного канала L1+L3, мм."""
        return self.L1 + self.L3

    @property
    def junction_x(self) -> float:
        """Координата X центра Т-образного стыка (= L1)."""
        return self.L1


def t_shape_outline(p: TReactorParams) -> List[Tuple[float, float]]:
    """Контур (2D, плоскость XY) Т-образной полости канала.

    Так как высота h одинакова и для главного, и для бокового
    канала (см. сечение А-А на чертеже), всё тело реактора -- это
    просто призма: плоский Т-образный контур, "выдавленный" по Z на
    величину h. Такой подход даёт ГАРАНТИРОВАННО замкнутое
    (watertight) тело без необходимости в трёхмерной булевой
    операции над объёмными боксами, которая для тонких
    высоко-аспектных боксов с совпадающими гранями по Z численно
    неустойчива (см. vtk_backend.py).

    Контур обходится против часовой стрелки, начиная с левого
    верхнего угла главного канала.
    """
    x0, x1 = 0.0, p.total_length
    y_top, y_bot = p.w / 2.0, -p.w / 2.0
    xL = p.junction_x - p.wd / 2.0
    xR = p.junction_x + p.wd / 2.0
    y_branch = -(p.w / 2.0 + p.L2)

    return [
        (x0, y_top),
        (x1, y_top),
        (x1, y_bot),
        (xR, y_bot),
        (xR, y_branch),
        (xL, y_branch),
        (xL, y_bot),
        (x0, y_bot),
    ]


def main_body_wall_rects(p: TReactorParams) -> List[List[Tuple[float, float, float]]]:
    """Прямоугольные стенки основного тела (боковые "вертикальные"
    грани призмы), КРОМЕ трёх портовых торцов -- те остаются
    открытыми (сквозными отверстиями), чтобы их отдельно закрывали
    "крышки" (см. cap_boxes). Крышки + эти стенки + верх/низ вместе
    образуют полностью замкнутый объём.

    Каждая стенка возвращается как список из 4 вершин (x,y,z) в
    порядке обхода (не обязательно "наружу" -- ориентация
    выставляется бэкендом при построении полигона).
    """
    outline = t_shape_outline(p)
    n = len(outline)
    # Индексы рёбер контура (см. t_shape_outline): 1,4,7 -- открытые
    # порты (outlet, inlet_2, inlet_1 соответственно), остальные --
    # обычные стенки.
    open_edge_indices = {1, 4, 7}
    walls = []
    for i in range(n):
        if i in open_edge_indices:
            continue
        x1, y1 = outline[i]
        x2, y2 = outline[(i + 1) % n]
        walls.append([
            (x1, y1, 0.0),
            (x2, y2, 0.0),
            (x2, y2, p.h),
            (x1, y1, p.h),
        ])
    return walls


def port_specs(p: TReactorParams) -> Dict[str, dict]:
    """Геометрия трёх портов (входов/выходов) реактора.

    Для каждого порта возвращает словарь с:
      - 'axis'   : 0/1/2 -> ось X/Y/Z, вдоль которой смотрит порт
      - 'sign'   : -1 или +1, направление нормали (наружу из тела)
      - 'coord'  : координата торцевой плоскости порта вдоль axis
      - 'u_range', 'v_range' : диапазоны двух других координат
        (то есть форма поперечного сечения порта)
    """
    return {
        "inlet_1": dict(
            axis=0, sign=-1, coord=0.0,
            u_range=(-p.w / 2.0, p.w / 2.0),  # Y
            v_range=(0.0, p.h),                # Z
        ),
        "outlet": dict(
            axis=0, sign=+1, coord=p.total_length,
            u_range=(-p.w / 2.0, p.w / 2.0),  # Y
            v_range=(0.0, p.h),                # Z
        ),
        "inlet_2": dict(
            axis=1, sign=-1, coord=-(p.w / 2.0 + p.L2),
            u_range=(p.junction_x - p.wd / 2.0, p.junction_x + p.wd / 2.0),  # X
            v_range=(0.0, p.h),                                              # Z
        ),
    }


def cap_boxes(p: TReactorParams) -> Dict[str, BoxSpec]:
    """Боксы трёх "крышек" портов.

    Каждая крышка -- тонкая пластина толщиной cap_thickness,
    вплотную примыкающая своей внутренней гранью к соответствующему
    торцу канала и точно повторяющая его поперечное сечение
    (w x h для главного канала, wd x h для бокового).
    Такое разбиение удобно для последующей триангуляции CFD-сетки:
    основное тело задаёт стенки (wall), а три отдельные крышки можно
    использовать как отдельные патчи inlet_1/inlet_2/outlet, либо как
    самостоятельные физические детали (переходники под трубки/фитинги).
    """
    ports = port_specs(p)
    boxes: Dict[str, BoxSpec] = {}
    for name, spec in ports.items():
        axis = spec["axis"]
        sign = spec["sign"]
        coord = spec["coord"]
        u0, u1 = spec["u_range"]
        v0, v1 = spec["v_range"]

        if sign < 0:
            along = (coord - p.cap_thickness, coord)
        else:
            along = (coord, coord + p.cap_thickness)

        if axis == 0:      # нормаль по X -> сечение в Y,Z
            box = (along[0], along[1], u0, u1, v0, v1)
        elif axis == 1:    # нормаль по Y -> сечение в X,Z
            box = (u0, u1, along[0], along[1], v0, v1)
        else:               # нормаль по Z -> сечение в X,Y (не используется здесь)
            box = (u0, u1, v0, v1, along[0], along[1])
        boxes[name] = box
    return boxes


def bounding_box(p: TReactorParams) -> BoxSpec:
    """Габаритный параллелепипед всей сборки (тело + крышки), мм."""
    outline = t_shape_outline(p)
    all_boxes: List[BoxSpec] = [
        (min(x for x, _ in outline), max(x for x, _ in outline),
         min(y for _, y in outline), max(y for _, y in outline),
         0.0, p.h)
    ] + list(cap_boxes(p).values())
    xs = [c for b in all_boxes for c in (b[0], b[1])]
    ys = [c for b in all_boxes for c in (b[2], b[3])]
    zs = [c for b in all_boxes for c in (b[4], b[5])]
    return (min(xs), max(xs), min(ys), max(ys), min(zs), max(zs))


